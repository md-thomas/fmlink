"""
OpenWave forward error correction: convolutional encoding + hard-decision
Viterbi decoding.

Per OpenWave_Specification.txt's modem chain (Packet Builder -> FEC Encoder ->
Interleaver -> Modulator), FEC protects the Header+Payload+CRC32 - NOT the
preamble/sync-word, which must stay raw/uncoded so openwave_sync.py's
correlator has a known, fixed reference pattern to find sync against in the
first place. See fec_encode.py/fec_decode.py for how a full frame is split
into (unprotected prefix, FEC-coded header, FEC-coded payload+CRC,
unprotected suffix).

Fully parameterized by generator polynomials (octal, standard convention)
and constraint length K, rather than hardcoded to one scheme - the point is
to be able to sweep/compare configurations easily. PRESETS below are a
starting set; tasklist.txt names the classic NASA/Voyager rate-1/2 K=7 code
(R1_2_K7) as the baseline candidate.

Bit convention (internal, not required to match any external standard -
nothing else in this project has FEC yet to interoperate with): the
register's bit 0 is the newest input bit, bit (K-1) is the oldest bit still
in the window. Generator polynomials are K-bit patterns interpreted against
that same register. This is self-consistent between encode/decode, which is
all that actually matters - see tests/test_openwave_fec.py for round-trip
and error-correction verification rather than relying on the convention
matching a textbook's exact bit order.

Each block's coded bits are then interleaved (DEFAULT_INTERLEAVER - see
interleave_permutation()) before byte padding, so a burst of consecutive
channel errors, e.g. an FM fade, reaches the Viterbi decoder as scattered
errors it can correct rather than one run it can't.

Each block is flushed with K-1 zero tail bits so the decoder can rely on
the trellis ending at state 0 - this adds redundancy per block (worse for
small blocks), which is part of why the header and payload+CRC are each
their own block rather than the whole frame being one giant block.
"""
