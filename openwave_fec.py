def _parity(value, k):
    return bin(value & ((1 << k) - 1)).count('1') % 2


def _build_transition_table(generators, k):
    """{state: {input_bit: (next_state, output_bits_tuple)}} for every
    state (0..2**(k-1)-1)."""
    num_states = 1 << (k - 1)
    state_mask = num_states - 1
    table = {}
    for state in range(num_states):
        table[state] = {}
        for b in (0, 1):
            full_register = (state << 1) | b
            outputs = tuple(_parity(full_register & g, k) for g in generators)
            next_state = full_register & state_mask
            table[state][b] = (next_state, outputs)
    return table


def free_distance(generators, k):
    """The code's free distance: the minimum total output Hamming weight
    over any path that diverges from the all-zero state and later
    remerges with it. This is THE standard quality metric for a
    convolutional code - larger free distance means more error-correction
    capability (a code is guaranteed to correct any pattern of up to
    floor((dfree-1)/2) errors). Computed exactly via Dijkstra over the
    trellis (edge weight = output Hamming weight for that transition),
    not estimated - see find_generators(), which uses this to pick good
    generator sets instead of guessing them by hand (see this module's
    changelog/history: an earlier hand-picked r1_3_k7 preset turned out to
    have out-of-range generator values that were silently truncated -
    exactly the kind of mistake this function exists to avoid)."""
    table = _build_transition_table(generators, k)

    start_state, start_outputs = table[0][1]  # diverge from state 0 via input=1
    start_weight = sum(start_outputs)
    if start_state == 0:
        return start_weight  # degenerate: immediate remerge

    best = {start_state: start_weight}
    pq = [(start_weight, start_state)]
    visited = set()
    while pq:
        d, state = heapq.heappop(pq)
        if state in visited:
            continue
        visited.add(state)
        if state == 0:
            return d
        for b in (0, 1):
            next_state, outputs = table[state][b]
            nd = d + sum(outputs)
            if next_state not in best or nd < best[next_state]:
                best[next_state] = nd
                heapq.heappush(pq, (nd, next_state))
    raise RuntimeError('no path back to state 0 found - degenerate generator set')


def find_generators(rate_denominator, k, num_candidates=3000, seed=0):
    """Randomly search for a good generator set: rate_denominator distinct
    K-bit values, each with bit0=1 (a generator with bit0=0 would never
    let the newest input bit affect that output at all - a degenerate,
    pointless choice), scored by free_distance() and returning the best
    one found. Not exhaustive/provably optimal, but principled - see
    free_distance()'s docstring for why this replaces guessing polynomial
    values by hand or from half-remembered tables."""
    rng = np.random.default_rng(seed)
    candidates = [v for v in range(1, 1 << k) if v & 1]  # bit0=1 required
    if rate_denominator > len(candidates):
        raise ValueError(
            f'rate 1/{rate_denominator} is not achievable at K={k}: only '
            f'{len(candidates)} distinct valid (bit0=1) generator values exist '
            f'for a {k}-bit register, so {rate_denominator} distinct generators '
            f"can't be chosen. Max achievable rate at this K is "
            f'1/{len(candidates)}.')
    best_generators = None
    best_distance = -1
    for _ in range(num_candidates):
        chosen = rng.choice(candidates, size=rate_denominator, replace=False)
        generators = tuple(int(v) for v in chosen)
        try:
            d = free_distance(generators, k)
        except RuntimeError:
            continue
        if d > best_distance:
            best_distance = d
            best_generators = generators
    return best_generators, best_distance


def coded_bit_length(num_input_bits, generators, k):
    """Exact output length (bits) of convolutional_encode() for
    num_input_bits input bits, including the K-1 zero-bit flush tail."""
    return (num_input_bits + k - 1) * len(generators)


def convolutional_encode(bits, generators, k):
    """Encode a list of 0/1 input bits. Output is
    coded_bit_length(len(bits), generators, k) bits long - always flushed
    with K-1 zero tail bits so decoding can rely on ending at state 0."""
    state = 0
    state_mask = (1 << (k - 1)) - 1
    out = []
    for b in list(bits) + [0] * (k - 1):
        full_register = (state << 1) | b
        for g in generators:
            out.append(_parity(full_register & g, k))
        state = full_register & state_mask
    return out


@functools.lru_cache(maxsize=None)
def _build_butterfly_tables(generators, k):
    """Predecessor form of _build_transition_table(), shaped for a fully
    vectorized (numpy, no per-state Python loop) Viterbi recursion.

    For this shift-register structure, next_state = ((state % (num_states //
    2)) << 1) | b - i.e. the OLD top bit of state gets shifted out and
    forgotten, and b becomes the new bottom bit. That means exactly two
    states can transition into any given next_state (they differ only in
    the bit that gets shifted out), and - critically - both of them do so
    via the SAME input bit b = next_state & 1 (b is a function of
    next_state alone, not of which predecessor won). That's what makes this
    vectorizable: b never needs to be looked up or stored per-branch, only
    derived from the state during traceback.

    Returns (pred0, pred1, out0, out1), each shape (num_states, ...):
    pred0[ns]/pred1[ns] are the two predecessor states of ns, and
    out0[ns]/out1[ns] are the n output bits produced by each of those two
    transitions. Cached per (generators, k) since it's identical across
    every viterbi_decode() call for a given preset."""
    n = len(generators)
    num_states = 1 << (k - 1)
    half = num_states // 2
    table = _build_transition_table(generators, k)

    pred0 = np.arange(num_states, dtype=np.int64) >> 1
    pred1 = pred0 + half
    out0 = np.empty((num_states, n), dtype=np.int8)
    out1 = np.empty((num_states, n), dtype=np.int8)
    for ns in range(num_states):
        b = ns & 1
        _, outputs0 = table[int(pred0[ns])][b]
        _, outputs1 = table[int(pred1[ns])][b]
        out0[ns] = outputs0
        out1[ns] = outputs1
    return pred0, pred1, out0, out1


def viterbi_decode(coded_bits, generators, k, num_input_bits):
    """Hard-decision Viterbi decode. coded_bits must be exactly
    coded_bit_length(num_input_bits, generators, k) bits long. Returns the
    decoded num_input_bits (the flush tail is discarded, not returned).

    Vectorized with numpy (see _build_butterfly_tables()): the per-step
    add-compare-select over every state/branch is array ops across all
    states at once instead of a Python-level double loop, which is what
    made this the dominant cost of the FEC pipeline (e.g. ~55s of a 56s
    r1_2_k7 file transfer)."""
    n = len(generators)
    num_states = 1 << (k - 1)
    num_steps = num_input_bits + k - 1
    expected_len = num_steps * n
    if len(coded_bits) != expected_len:
        raise ValueError(f'coded_bits must be exactly {expected_len} bits '
                          f'for {num_input_bits} input bits at this rate/K, got {len(coded_bits)}')

    pred0, pred1, out0, out1 = _build_butterfly_tables(tuple(generators), k)
    received = np.asarray(coded_bits, dtype=np.int8).reshape(num_steps, n)

    path_metric = np.full(num_states, np.inf)
    path_metric[0] = 0  # encoder always starts at state 0
    backpointers = np.empty((num_steps, num_states), dtype=np.int64)

    for t in range(num_steps):
        r = received[t]
        errors0 = np.count_nonzero(out0 != r, axis=1)
        errors1 = np.count_nonzero(out1 != r, axis=1)
        cand0 = path_metric[pred0] + errors0
        cand1 = path_metric[pred1] + errors1
        take0 = cand0 <= cand1
        path_metric = np.where(take0, cand0, cand1)
        backpointers[t] = np.where(take0, pred0, pred1)

    # flushed with zero tail bits -> encoder always ends at state 0
    state = 0
    decoded = [0] * num_steps
    for t in range(num_steps - 1, -1, -1):
        decoded[t] = state & 1  # input bit into `state` is always its own LSB
        state = int(backpointers[t, state])
    return decoded[:num_input_bits]


def bit_error_count(a, b):
    """Count differing bits between two equal-length 0/1 sequences -
    useful for measuring how much damage a channel did, e.g. when
    comparing FEC configurations' effective error-correction capability."""
    return int(np.count_nonzero(np.asarray(a) != np.asarray(b)))


def _pad_to_byte(bits):
    """Pad a bit list with zero bits up to the next multiple of 8."""
    remainder = len(bits) % 8
    return bits if remainder == 0 else bits + [0] * (8 - remainder)


# -- interleaving ------------------------------------------------------------
# Reorders each FEC block's coded bits (before byte padding) so a burst of
# consecutive channel errors - an FM fade, a click - lands on coded bits
# spread far apart in the code's own order, where Viterbi sees scattered,
# correctable errors instead of one uncorrectable run.
INTERLEAVERS = ('none', 'block', 'golden')
# What encode_frame()/decode_frames() use unless told otherwise - see the
# FEC section of OpenWave_Specification.txt. Under mobile FM fading, golden
# took mode 2/r1_2_k7 at 15 dB CNR, 80 km/h from 38% of frames delivered
# (no interleaving) to 100%; block interleaving did nearly as well (it left
# slightly more failures), and golden is a one-line rule to specify.
DEFAULT_INTERLEAVER = 'golden'


@functools.lru_cache(maxsize=256)
def interleave_permutation(n, scheme):
    """perm such that interleaved[j] = coded[perm[j]], for an n-bit block.
    'block': write row by row into ceil(sqrt(n)) columns, read column by
    column (pruned at n). 'golden': perm[j] = (j * s) mod n, s the integer
    nearest n*(sqrt(5)-1)/2 that is coprime with n - consecutive channel
    bits come from code positions s apart, and any run of them is spread
    near-evenly across the block."""
    if scheme == 'none' or n <= 1:
        return np.arange(n)
    if scheme == 'block':
        cols = int(np.ceil(np.sqrt(n)))
        rows = -(-n // cols)
        grid = np.arange(rows * cols).reshape(rows, cols)
        order = grid.T.ravel()
        return order[order < n]
    if scheme == 'golden':
        target = n * (np.sqrt(5) - 1) / 2
        s = int(round(target))
        offset = 0
        while True:
            for candidate in (s + offset, s - offset):
                if 0 < candidate < n and np.gcd(candidate, n) == 1:
                    return (np.arange(n) * candidate) % n
            offset += 1
    raise ValueError(f"unknown interleaver {scheme!r} (one of {INTERLEAVERS})")


def interleave_bits(bits, scheme):
    """Coded bits (code order) -> channel order. Returns a list of ints."""
    return np.asarray(bits)[interleave_permutation(len(bits), scheme)].tolist()


def deinterleave_bits(bits, scheme):
    """Inverse of interleave_bits(): channel order -> code order."""
    bits = np.asarray(bits)
    out = np.empty_like(bits)
    out[interleave_permutation(len(bits), scheme)] = bits
    return out.tolist()


def _coded_byte_length(num_input_bits, generators, k):
    """Byte length of an independently-flushed, byte-padded FEC block
    encoding num_input_bits input bits - see encode_frame()."""
    return (coded_bit_length(num_input_bits, generators, k) + 7) // 8


def encode_frame(data, generators, k, interleaver=DEFAULT_INTERLEAVER):
    """FEC-encode one or more frames produced by openwave_link.build_frame()
    or build_fragmented_frames() - each frame found is processed
    independently and in order (matching how build_fragmented_frames()
    itself treats every fragment as a fully independent over-the-air
    burst, not one continuous stream). For each frame: its lead-pad/
    preamble/sync-word prefix and end-pad suffix pass through completely
    UNCHANGED (per this module's docstring - they must stay raw for
    openwave_sync.py's correlator); its Header block and Payload+CRC block
    are each independently convolutionally encoded (own flush tail) and
    zero-padded to a whole number of bytes.

    An earlier version of this function only found and encoded the FIRST
    frame in data, silently passing every subsequent fragment through
    completely unprotected (misreading them as harmless trailing
    padding) - a multi-fragment message would report a clean decode while
    silently missing everything past fragment 1. See
    tests/test_openwave_fec.py's multi-fragment tests.

    Returns the new (longer) byte stream. This is TX-side: data is assumed
    clean/uncorrupted (nothing to be tolerant of yet), so each frame is
    found via an exact preamble+sync-word match, same as
    openwave_link.build_frame()'s own output always allows."""
    marker = link.PREAMBLE + link.SYNC_WORD
    result = bytearray()
    pos = 0
    found_any = False

    while True:
        idx = data.find(marker, pos)
        if idx == -1:
            result += data[pos:]  # trailing bytes after the last frame (end_pad)
            break
        found_any = True
        result += data[pos:idx]  # this frame's own lead_pad, if any - unchanged

        header_start = idx + len(marker)
        header_bytes = data[header_start:header_start + link.HEADER_LEN]
        if len(header_bytes) < link.HEADER_LEN:
            result += data[idx:]  # truncated - nothing more to encode
            break

        header = link.parse_header(header_bytes)
        payload_crc_len = header['payload_len'] + link.CRC_LEN
        payload_start = header_start + link.HEADER_LEN
        payload_crc_bytes = data[payload_start:payload_start + payload_crc_len]

        result += marker  # preamble+sync word stay raw
        header_bits = modem.bytes_to_bits(header_bytes)
        payload_crc_bits = modem.bytes_to_bits(payload_crc_bytes)
        for block_bits in (header_bits, payload_crc_bits):
            coded = interleave_bits(convolutional_encode(block_bits, generators, k), interleaver)
            result += modem.bits_to_bytes(_pad_to_byte(coded))

        pos = payload_start + payload_crc_len  # continue right after this frame's CRC

    if not found_any:
        raise ValueError('no preamble+sync-word found - is this a build_frame() output?')
    return bytes(result)


def decode_frames(data, generators, k, max_error_fraction=sync.DEFAULT_MAX_ERROR_FRACTION,
                  interleaver=DEFAULT_INTERLEAVER, first_marker_bit=None):
    """Find and decode every frame in possibly-corrupted data (via
    openwave_sync's tolerant correlator - the prefix/preamble/sync-word
    were never FEC-coded, so this is the same sync step as the uncoded
    path), yielding one (status, header, payload) per frame found, in
    order. For each frame: Viterbi-decode its Header block, then its
    Payload+CRC block (whose length depends on the header's decoded
    payload_len - see module docstring), correcting bit errors within the
    code's capability, then advance past it and look for the next one -
    matching how encode_frame() FEC-protects each fragment of a
    build_fragmented_frames() message independently rather than treating
    the whole multi-fragment message as one block. (An earlier version of
    this function, decode_received(), only ever found/decoded ONE frame -
    silently missing every fragment past the first in a multi-fragment
    message. See fec_decode.py for how the yielded per-fragment results
    get reassembled into one clean output stream, and
    tests/test_openwave_fec.py's multi-fragment tests.)

    Each yielded status is one of:
      'gap'        - every marker, including the first, is searched for
                     within sync.FRAGMENT_GAP_SEARCH_BITS of where the
                     previous one ended (or of pos=0, for the first). If
                     nothing clears the threshold that nearby, this is
                     yielded (header/payload both None) and the search
                     falls back to unbounded so later fragments can still
                     be found. Without this, an unbounded search would
                     just silently lock onto whatever real marker comes
                     next, however far away, with no indication a fragment
                     in between was lost - found via a 3dB/100-iteration
                     FEC sweep across presets where pass rates didn't
                     track code strength; a direct repro showed this
                     function yielding fragment seq 0, 2, 3, 4 with every
                     one reporting 'ok' - seq 1 had vanished with no error
                     at all. A second repro then showed the SAME thing
                     happening to fragment 0 itself (seq 1, 2, 3, 4 with
                     no seq 0) - an earlier version of this fix only
                     bounded the search after the first fragment synced,
                     since there's no well-defined "expected nearby
                     position" for a truly free-floating first search over
                     an arbitrary buffer in general. But for this
                     protocol's small fixed lead_pad (no real RF
                     idle-carrier capture path exists yet), treating the
                     first marker the same as every other one is strictly
                     more informative: the common case (marker within the
                     window) is unaffected, and the case that used to
                     stay silent now doesn't (see
                     openwave_sync.FRAGMENT_GAP_SEARCH_BITS).
      'bad_length' - header decoded, but its payload_len is out of range
                     (scanning continues past just this header block, in
                     case a real frame follows)
      'truncated'  - not enough data remains for a complete block (stops -
                     nothing coherent can follow a truncated frame)
      'crc_fail'   - both blocks decoded, but the CRC over the corrected
                     bytes still doesn't match (FEC failed to fully
                     correct this frame - correction isn't guaranteed
                     beyond the code's statistical capability, so this is
                     always re-checked rather than trusting Viterbi output
                     blindly)
      'ok'         - decoded and CRC-verified; header/payload are the
                     corrected values

    first_marker_bit: where the first frame's marker starts, when the caller
    already knows - e.g. openwave_audio.demodulate() found it by correlating
    against the received samples, which is far more robust than matching
    the marker's hard-decision bits (a fade across the marker can push it
    past max_error_fraction while the FEC-protected header and payload
    behind it are still decodable). That frame is decoded at exactly that
    position with no bit-level threshold; any later frames are searched
    for as usual.

    Yields nothing at all if no sync candidate ever clears the
    correlator's threshold (the multi-frame analogue of the old
    'no_sync' status - check for an empty result rather than a status)."""
    bits = modem.bytes_to_bits(data)
    pos = 0
    while True:
        if first_marker_bit is not None:
            match, pos, first_marker_bit = (first_marker_bit, None), 0, None
        else:
            match = sync.best_sync_offset(bits[pos:], max_error_fraction=max_error_fraction,
                                           search_window=sync.FRAGMENT_GAP_SEARCH_BITS)
        if match is None:
            match = sync.best_sync_offset(bits[pos:], max_error_fraction=max_error_fraction)
            if match is None:
                return
            yield 'gap', None, None

        rel_offset, _errors = match
        marker_start = pos + rel_offset
        header_block_start = marker_start + sync.MARKER_LEN

        header_input_bits = link.HEADER_LEN * 8
        header_block_bytes = _coded_byte_length(header_input_bits, generators, k)
        header_block_bits = bits[header_block_start:header_block_start + header_block_bytes * 8]
        if len(header_block_bits) < header_block_bytes * 8:
            yield 'truncated', None, None
            return

        coded_header_len = coded_bit_length(header_input_bits, generators, k)
        header_bits = viterbi_decode(deinterleave_bits(header_block_bits[:coded_header_len], interleaver),
                                     generators, k, header_input_bits)
        header_bytes = modem.bits_to_bytes(header_bits)
        header = link.parse_header(header_bytes)

        if not (0 <= header['payload_len'] <= link.MAX_PAYLOAD_LEN):
            yield 'bad_length', header, None
            pos = header_block_start + header_block_bytes * 8
            continue

        payload_input_bits = (header['payload_len'] + link.CRC_LEN) * 8
        payload_block_bytes = _coded_byte_length(payload_input_bits, generators, k)
        payload_block_start = header_block_start + header_block_bytes * 8
        payload_block_bits = bits[payload_block_start:payload_block_start + payload_block_bytes * 8]
        if len(payload_block_bits) < payload_block_bytes * 8:
            yield 'truncated', header, None
            return

        coded_payload_len = coded_bit_length(payload_input_bits, generators, k)
        payload_crc_bits = viterbi_decode(deinterleave_bits(payload_block_bits[:coded_payload_len], interleaver),
                                          generators, k, payload_input_bits)
        payload_crc_bytes = modem.bits_to_bytes(payload_crc_bits)
        payload = payload_crc_bytes[:header['payload_len']]
        crc_bytes = payload_crc_bytes[header['payload_len']:]

        received_crc, = struct.unpack('>I', crc_bytes)
        status = ('ok' if (zlib.crc32(header_bytes + payload) & 0xFFFFFFFF) == received_crc
                  else 'crc_fail')
        yield status, header, payload

        pos = payload_block_start + payload_block_bytes * 8
